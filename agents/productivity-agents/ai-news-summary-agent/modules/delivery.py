from __future__ import annotations
import os
import smtplib
import urllib.parse
from email.mime.multipart import MIMEMultipart
from email.mime.text import MIMEText


# ── Email ─────────────────────────────────────────────────────────────────────

def send_email_digest(
    to_addr: str,
    subject: str,
    body_text: str,
    body_html: str = "",
    smtp_host: str = "",
    smtp_port: int = 587,
    smtp_user: str = "",
    smtp_pass: str = "",
) -> tuple[bool, str]:
    """Send the daily digest via SMTP."""
    host = smtp_host or os.environ.get("SMTP_HOST", "smtp.gmail.com")
    port = smtp_port or int(os.environ.get("SMTP_PORT", 587))
    user = smtp_user or os.environ.get("SMTP_USER", "")
    pwd = smtp_pass or os.environ.get("SMTP_PASS", "")

    if not user or not pwd:
        return False, "SMTP credentials not configured."

    try:
        msg = MIMEMultipart("alternative")
        msg["Subject"] = subject
        msg["From"] = user
        msg["To"] = to_addr

        msg.attach(MIMEText(body_text, "plain"))
        if body_html:
            msg.attach(MIMEText(body_html, "html"))

        with smtplib.SMTP(host, port) as server:
            server.ehlo()
            server.starttls()
            server.login(user, pwd)
            server.sendmail(user, to_addr, msg.as_string())
        return True, "Email sent successfully!"
    except Exception as e:
        return False, str(e)


