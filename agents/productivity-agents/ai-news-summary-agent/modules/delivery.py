# ── WhatsApp ──────────────────────────────────────────────────────────────────

def build_whatsapp_message(digest: dict, articles: list[dict]) -> str:
    """Build a compact WhatsApp-friendly message (< 1000 chars)."""
    date = digest.get("title", "Daily Brief").replace("Morning Intelligence Brief — ", "")
    overview = digest.get("overview", "")[:300]
    themes = " · ".join(digest.get("key_themes", [])[:3])

    top_stories = sorted(articles, key=lambda x: x.get("signal_score", 0), reverse=True)[:3]
    stories_text = "\n".join([
        f"• {a['title'][:70]}" for a in top_stories
    ])

    return f"""📰 *AI News Brief — {date}*

{overview}

*Top Themes:* {themes}

*Top Stories:*
{stories_text}

_Powered by AI News Agent_"""


def get_whatsapp_link(phone: str, message: str) -> str:
    """Generate a wa.me share link."""
    encoded = urllib.parse.quote(message)
    clean_phone = phone.replace("+", "").replace(" ", "").replace("-", "")
    return f"https://wa.me/{clean_phone}?text={encoded}"


