# DOCX Export
# ─────────────────────────────────────────────

def export_docx(analysis: dict, transcript: str, follow_up_email: str) -> bytes:
    """Generate a Word document using python-docx."""
    try:
        from docx import Document
        from docx.shared import Pt, RGBColor, Inches
        from docx.enum.text import WD_ALIGN_PARAGRAPH

        doc = Document()

        # Page margins
        for section in doc.sections:
            section.top_margin = Inches(0.75)
            section.bottom_margin = Inches(0.75)
            section.left_margin = Inches(1)
            section.right_margin = Inches(1)

        INDIGO = RGBColor(0x4f, 0x46, 0xe5)
        DARK = RGBColor(0x0f, 0x17, 0x2a)
        GRAY = RGBColor(0x64, 0x74, 0x8b)

        def add_heading(text, level=1, color=None):
            p = doc.add_heading(text, level=level)
            if color:
                for run in p.runs:
                    run.font.color.rgb = color
            return p

        def add_para(text, bold=False, color=None, size=10):
            p = doc.add_paragraph()
            run = p.add_run(text)
            run.bold = bold
            run.font.size = Pt(size)
            if color:
                run.font.color.rgb = color
            return p

        def add_bullet(text, color=None):
            p = doc.add_paragraph(text, style="List Bullet")
            if color:
                for run in p.runs:
                    run.font.color.rgb = color
            return p

        # Title
        title_para = doc.add_heading(analysis.get("title", "Meeting Notes"), 0)
        for run in title_para.runs:
            run.font.color.rgb = DARK
            run.font.size = Pt(20)

        add_para(f"Date: {analysis.get('date_mentioned', _format_date())}", color=GRAY)
        add_para(f"Attendees: {', '.join(analysis.get('attendees', ['Not specified']))}", color=GRAY)
        add_para(f"Sentiment: {analysis.get('sentiment', '')}  |  Effectiveness: {analysis.get('meeting_effectiveness', '')}", color=GRAY)
        doc.add_paragraph("─" * 60)

        # Summary
        add_heading("Executive Summary", 1, INDIGO)
        doc.add_paragraph(analysis.get("summary", ""))

        # Key Topics
        topics = analysis.get("key_topics", [])
        if topics:
            add_heading("Key Topics", 1, INDIGO)
            for t in topics:
                add_bullet(t)

        # Decisions
        decisions = analysis.get("decisions", [])
        if decisions:
            add_heading("Decisions Made", 1, INDIGO)
            for i, d in enumerate(decisions, 1):
                add_para(f"{i}. {d['decision']}", bold=True)
                add_para(f"   Owner: {d.get('owner','TBD')} | {d.get('context','')}", color=GRAY)

        # Action Items
        action_items = analysis.get("action_items", [])
        if action_items:
            add_heading("Action Items", 1, INDIGO)
            table = doc.add_table(rows=1, cols=5)
            table.style = "Table Grid"
            hdr = table.rows[0].cells
            for i, h in enumerate(["#", "Task", "Owner", "Deadline", "Priority"]):
                hdr[i].text = h
                for para in hdr[i].paragraphs:
                    for run in para.runs:
                        run.bold = True
            for i, ai in enumerate(action_items, 1):
                row = table.add_row().cells
                row[0].text = str(i)
                row[1].text = ai.get("task", "")
                row[2].text = ai.get("owner", "TBD")
                row[3].text = ai.get("deadline", "TBD")
                row[4].text = ai.get("priority", "Medium")

        # Tasks by Person
        tasks_by_person = analysis.get("tasks_by_person", {})
        if tasks_by_person:
            add_heading("Tasks by Person", 1, INDIGO)
            for person, tasks in tasks_by_person.items():
                add_para(person, bold=True)
                for task in tasks:
                    add_bullet(f"  {task}")

        # Risks
        risks = analysis.get("risks_blockers", [])
        if risks:
            add_heading("Risks & Blockers", 1, INDIGO)
            for r in risks:
                add_bullet(f"⚠ {r}")

        # Follow-up Email
        if follow_up_email:
            doc.add_page_break()
            add_heading("Follow-up Email Draft", 1, INDIGO)
            for line in follow_up_email.split("\n"):
                p = doc.add_paragraph(line or " ")
                p.runs[0].font.size = Pt(10) if p.runs else None

        # Transcript
        doc.add_page_break()
        add_heading("Full Transcript", 1, INDIGO)
        p = doc.add_paragraph(transcript)
        p.runs[0].font.size = Pt(9)

        add_para(f"Generated by AI Meeting Notes Agent · {_format_date()}", color=GRAY)

        buf = io.BytesIO()
        doc.save(buf)
        buf.seek(0)
        return buf.read()

    except ImportError:
        return b"python-docx not installed. Run: pip install python-docx"
    except Exception as e:
        return f"DOCX generation error: {e}".encode()
